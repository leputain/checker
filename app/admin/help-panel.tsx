function FeatureGrid({ items, onNavigate }: {
  items: HelpCard[];
  onNavigate: (target: AdminHelpTarget) => void;
}) {
  return (
    <div className={styles.helpGrid}>
      {items.map((item, index) => {
        const target = item.target;
        return <article className={styles.helpCard} key={item.title}>
          <header>
            <span aria-hidden="true">{String(index + 1).padStart(2, '0')}</span>
            <h3>{item.title}</h3>
          </header>
          <p>{item.description}</p>
          <ul>{item.details.map((detail) => <li key={detail}>{detail}</li>)}</ul>
          {target && (
            <button type="button" onClick={() => onNavigate(target)}>
              Открыть раздел <span aria-hidden="true">→</span>
            </button>
          )}
        </article>;
      })}
    </div>
  );
}

